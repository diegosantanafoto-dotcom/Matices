#!/usr/bin/env node
// scripts/generate-portfolio.js
// Escanea public/images/* y genera src/data/portfolioData.ts automáticamente

import { execSync } from 'child_process';
import { readdirSync, writeFileSync, statSync } from 'fs';
import { join, basename, extname } from 'path';

const ROOT = process.cwd();
const PUBLIC = join(ROOT, 'public', 'images');
const OUTPUT = join(ROOT, 'src', 'data', 'portfolioData.ts');

const CATEGORIES = {
  weddings:  { id: 'bodas',     label: 'Bodas',     name: 'Bodas' },
  lifestyle: { id: 'lifestyle', label: 'Lifestyle',  name: 'Lifestyle' },
  retratos:  { id: 'retratos',  label: 'Retratos',  name: 'Retratos' },
  moda:      { id: 'moda',      label: 'Moda',       name: 'Moda' },
  marcas:    { id: 'marcas',    label: 'Marcas',     name: 'Marcas' },
};

function getDims(filePath) {
  try {
    const out = execSync(`sips -g pixelWidth -g pixelHeight "${filePath}" 2>/dev/null`).toString();
    const w = parseInt((out.match(/pixelWidth:\s*(\d+)/) || [])[1] || '0');
    const h = parseInt((out.match(/pixelHeight:\s*(\d+)/) || [])[1] || '0');
    return { w, h };
  } catch {
    return { w: 0, h: 0 };
  }
}

function hashString(str) {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash << 5) - hash + str.charCodeAt(i);
    hash |= 0;
  }
  return Math.abs(hash);
}

function aspectClass(w, h, id = '') {
  const hash = hashString(id);
  const portraitRatios = ['aspect-[2/3]', 'aspect-[3/4]', 'aspect-[4/5]', 'aspect-[9/14]', 'aspect-[2/3]', 'aspect-[3/4]', 'aspect-[4/5]', 'aspect-[3/5]'];
  const landscapeRatios = ['aspect-[3/2]', 'aspect-[4/3]', 'aspect-[16/9]', 'aspect-square', 'aspect-[3/2]', 'aspect-[4/3]', 'aspect-[5/4]'];

  if (w === 0 || h === 0) return portraitRatios[hash % portraitRatios.length];
  const ratio = w / h;
  if (ratio > 1.1) return landscapeRatios[hash % landscapeRatios.length];
  if (ratio < 0.9) return portraitRatios[hash % portraitRatios.length];
  return 'aspect-square';
}

function safeId(folder, filename) {
  return `${folder}-${filename.replace(/[^a-zA-Z0-9]/g, '-').replace(/-+/g, '-').replace(/^-|-$/g, '')}`;
}

const entries = [];

for (const [folder, cat] of Object.entries(CATEGORIES)) {
  const dir = join(PUBLIC, folder);
  let files;
  try {
    files = readdirSync(dir).filter(f => /\.(jpg|jpeg|png|webp)$/i.test(f));
  } catch { continue; }

  for (const file of files.sort()) {
    const fullPath = join(dir, file);
    try { statSync(fullPath); } catch { continue; }

    const id = safeId(cat.id, basename(file, extname(file)));
    const { w, h } = getDims(fullPath);
    const ac = aspectClass(w, h, id);
    const imgUrl = `/images/${folder}/${file}`;

    entries.push({
      id,
      category: cat.id,
      categoryLabel: cat.label,
      imageUrl: imgUrl,
      aspectRatioClass: ac,
    });
  }
}

const header = `// AUTO-GENERATED by scripts/generate-portfolio.js — DO NOT EDIT MANUALLY
// Run: node scripts/generate-portfolio.js

export interface ExifData {
  camera: string;
  lens: string;
  aperture: string;
  shutterSpeed: string;
  iso: string;
  lighting: string;
}

export interface PortfolioItem {
  id: string;
  title: string;
  category: 'bodas' | 'lifestyle' | 'retratos' | 'moda' | 'marcas';
  categoryLabel: string;
  client: string;
  year: string;
  location: string;
  imageUrl: string;
  aspectRatioClass: string;
  description: string;
  exif: ExifData;
}

const defaultExif: ExifData = {
  camera: 'Sony Alpha 1',
  lens: 'Sony FE 50mm f/1.2 GM',
  aperture: 'f/2.0',
  shutterSpeed: '1/800s',
  iso: 'ISO 100',
  lighting: 'Luz natural',
};

export const PORTFOLIO_ITEMS: PortfolioItem[] = [
`;

const footer = `];\n`;

const items = entries.map(e => `  {
    id: ${JSON.stringify(e.id)},
    title: 'matices.ch',
    category: ${JSON.stringify(e.category)},
    categoryLabel: ${JSON.stringify(e.categoryLabel)},
    client: 'matices.ch',
    year: '2025',
    location: 'Tenerife, Canarias',
    imageUrl: ${JSON.stringify(e.imageUrl)},
    aspectRatioClass: ${JSON.stringify(e.aspectRatioClass)},
    description: '',
    exif: defaultExif,
  }`).join(',\n');

writeFileSync(OUTPUT, header + items + '\n' + footer, 'utf-8');
console.log(`✅ Generated ${entries.length} entries → ${OUTPUT}`);
